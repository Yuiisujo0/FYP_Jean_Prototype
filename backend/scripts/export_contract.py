"""Exports what the Cloudflare Worker needs from the Python reference implementation, plus golden test cases.

    python scripts/export_contract.py

Writes:
  src/pipeline/contract.ts     operations, JSON schema, catalogue text, example, library patterns
  backend/eval/golden.json     inputs and the exact outputs the Python code produces for them

The TypeScript pipeline (src/pipeline/) must reproduce the golden outputs exactly; tests/pipeline.test.ts checks that.
Python stays the reference: change a prompt or an operation here, re-run this script, then fix the TypeScript until
the golden test passes again.
"""
import json
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from app import config, db  # noqa: E402

config.DB_PATH = str(Path(tempfile.mkdtemp()) / "contract.db")   # never touch the user's database

from app.llm import EXAMPLE_ANSWER, EXAMPLE_REQUEST, build_flow, normalize_config, refine_messages, repair_message, revise_messages, system_prompt  # noqa: E402
from app.node_kinds import NODE_KINDS, catalogue_text  # noqa: E402
from app.retrieval import retrieve  # noqa: E402
from app.schema import DraftWorkflow, ValidationIssue, draft_json_schema  # noqa: E402

PROJECT = ROOT.parent
tasks = json.loads((ROOT / "eval" / "tasks.json").read_text(encoding="utf-8"))
library = sorted((t for t in tasks["tasks"] if t["split"] == "library"), key=lambda t: t["id"])
patterns = [{"id": t["id"], "title": t["title"], "request": t["request"], "steps": t["steps"], "verified": t["verified"]} for t in library]
db.replace_patterns("library", patterns)

config.SYNTAX_HINTS = True
with_hints = catalogue_text()
config.SYNTAX_HINTS = False
without_hints = catalogue_text()
config.SYNTAX_HINTS = True

contract = {
    "kinds": [{
        "type": k.type, "label": k.label, "defaultName": k.default_name, "defaultDescription": k.default_description,
        "required": list(k.required), "optional": list(k.optional), "isSource": k.is_source,
        "defaultConfig": k.default_config, "hint": k.hint,
    } for k in NODE_KINDS],
    "schema": draft_json_schema(),
    "catalogueWithHints": with_hints,
    "catalogueWithoutHints": without_hints,
    "exampleRequest": EXAMPLE_REQUEST,
    "exampleAnswer": EXAMPLE_ANSWER,
    "patterns": patterns,
}
(PROJECT / "src" / "pipeline").mkdir(exist_ok=True)
HEADER = (
    "// Generated by backend/scripts/export_contract.py from the Python reference implementation. Do not edit by hand.\n"
    "import type { Contract } from './types.ts';\n\n"
)
(PROJECT / "src" / "pipeline" / "contract.ts").write_text(
    HEADER + "export const contract: Contract = " + json.dumps(contract, indent=1, ensure_ascii=False) + ";\n",
    encoding="utf-8",
)

# ---------------- golden cases ----------------
many_columns = [f"col_{i}" for i in range(15)]
dataset_variants = {
    "none": None,
    "one": [{"name": "student_marks", "columns": ["student_id", "name", "course", "score"]}],
    "many": [{"name": f"data_{i}", "columns": many_columns if i == 0 else ["a", "b"]} for i in range(8)],
}
prompts = [t["request"] for t in tasks["tasks"] if t["split"] in ("dev", "test", "holdout")][:30] + [
    "Fetch posts from an API and summarise them with the model",
    "zzzz qqqq",
    "Read a CSV of student marks, keep those below 50, and save them to the database",
]

prompt_cases = []
for prompt in prompts:
    for label, datasets in dataset_variants.items():
        retrieved = retrieve(prompt, 2, "patterns")
        messages = [
            {"role": "system", "content": system_prompt(retrieved, datasets)},
            {"role": "user", "content": EXAMPLE_REQUEST},
            {"role": "assistant", "content": EXAMPLE_ANSWER},
            {"role": "user", "content": prompt},
        ]
        prompt_cases.append({"prompt": prompt, "datasets": datasets, "datasetsLabel": label,
                             "retrievedIds": [e.id for e in retrieved], "messages": messages})

drafts = [
    ("Read a CSV of student marks and keep the failing ones", [
        {"type": "READ_CSV", "file": " marks.csv ", "delimiter": ""}, {"type": "FILTER", "condition": "score < 50"},
        {"type": "TRANSFORM", "operation": "Select columns Name, Score"}, {"type": "DATABASE", "table": ""}, {"type": "OUTPUT", "format": "table"}]),
    ("Fetch data from an API and then do several unusual things with it so that the title gets cut", [
        {"type": "HTTP_REQUEST", "method": "get", "url": "https://api.example.com/a/very/long/path/that/should/be/shortened/in/the/name"},
        {"type": "LLM", "task": ""}, {"type": "OUTPUT", "format": "csv"}]),
    ("an unknown step", [{"type": "MYSTERY", "x": "y"}, {"type": "OUTPUT", "format": ""}]),
    ("input first", [{"type": "INPUT", "source": "manual"}, {"type": "READ_FILE", "file": "notes.txt"}, {"type": "OUTPUT", "format": "table"}]),
    ("filter long condition", [{"type": "READ_CSV", "file": "x", "delimiter": ";"},
                               {"type": "FILTER", "condition": "course == CS101 and attendance_pct < 70 and score >= 50 or name contains Lee"},
                               {"type": "OUTPUT", "format": "table"}]),
    ("Read marks, flag everyone below 50, then save them to the database", [
        {"type": "READ_CSV", "file": "student_marks", "delimiter": ","}, {"type": "FILTER", "condition": "score < 50"},
        {"type": "DATABASE", "table": "failed_students"}]),
]
build_cases = []
for prompt, steps in drafts:
    flow = build_flow(DraftWorkflow(steps=steps), prompt)
    build_cases.append({
        "prompt": prompt, "steps": steps,
        "expected": {"name": flow.name, "description": flow.description,
                     "nodes": [{"type": n.type, "name": n.name, "description": n.description, "config": n.config,
                                "position": n.position.model_dump() if n.position else None} for n in flow.nodes],
                     "edgeCount": len(flow.edges)},
    })

issues = [ValidationIssue(level="ERROR", message="End the workflow with an Output step."), ValidationIssue(level="WARNING", message="could use a description"),
          ValidationIssue(level="ERROR", message="Filter needs a value for “condition”.")]
by_id = {t["id"]: t for t in tasks["tasks"]}
refine_cases = []
for task_id, instruction in [
    ("S1", "Change the score limit to 40"), ("S2", "Add a step that keeps only the name and score columns"),
    ("O7", "Remove the step that saves to the database"), ("E3", "Sort the result by salary, highest first"),
    ("U1", "Make this simpler"), ("S3", "Also exclude students from MATH201"),
]:
    for label, datasets in dataset_variants.items():
        refine_cases.append({
            "taskId": task_id, "steps": by_id[task_id]["steps"], "instruction": instruction, "datasets": datasets,
            "datasetsLabel": label, "messages": refine_messages(by_id[task_id]["steps"], instruction, datasets),
        })

revise_cases = []
for task_id, observation in [
    ("S1", "Step 2 (FILTER: Keeps only the rows where score is less than 50.) 40 rows in, 0 rows out.\nThe result has 0 rows."),
    ("E3", "The run stopped with an error: “Filter” stopped the run. There is no column “pay”. Available columns: name, salary."),
    ("O7", "Step 2 (FILTER) 30 rows in, 30 rows out.\nColumn status in the data: 30 text values.\nThe result has 30 rows and the columns id, status."),
]:
    for label, datasets in dataset_variants.items():
        revise_cases.append({
            "taskId": task_id, "request": by_id[task_id]["request"], "steps": by_id[task_id]["steps"], "observation": observation,
            "datasets": datasets, "datasetsLabel": label,
            "messages": revise_messages(by_id[task_id]["request"], by_id[task_id]["steps"], observation, datasets),
        })

normalize_inputs = [
    ("READ_CSV", {"file": " x ", "delimiter": ""}), ("FILTER", {"condition": "", "note": ""}), ("MYSTERY", {"a": " b "}),
    ("LLM", {"task": ""}), ("HTTP_REQUEST", {"method": " get ", "url": "  "}), ("INPUT", {}), ("OUTPUT", {"format": "csv", "extra": " y "}),
]
normalize_cases = [{"type": t, "config": c, "expected": normalize_config(t, c)} for t, c in normalize_inputs]

golden = {"promptCases": prompt_cases, "buildCases": build_cases, "refineCases": refine_cases, "reviseCases": revise_cases, "normalizeCases": normalize_cases,
          "repairMessage": {"issues": [i.model_dump() for i in issues], "expected": repair_message(issues)}}
(ROOT / "eval" / "golden.json").write_text(json.dumps(golden, indent=1, ensure_ascii=False), encoding="utf-8")

print(f"contract.ts: {len(contract['kinds'])} operations, {len(patterns)} patterns")
print(f"golden.json: {len(prompt_cases)} prompt cases, {len(build_cases)} build cases, {len(refine_cases)} refine cases, {len(revise_cases)} revise cases, {len(normalize_cases)} normalize cases")
